  superimposed_patch = np.reshape(np.reshape(natural_images[np.random.randint(natural_images.shape[0]),:],[100,100])[loc[0]:loc[0]+28,:][:,loc[1]:loc[1]+28] ,[1,784])
  targetplus[i] = 1.5*foreground[i] + superimposed_patch

