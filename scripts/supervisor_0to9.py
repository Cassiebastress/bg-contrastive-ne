"""The supervisor report's MNIST-on-grass 0-9 table and figure, generated from results/mnist_grass_0to9/ (no number
typed by hand; nothing is recomputed except the plot).

- docs/supervisor_report/generated/tab_mnist09.tex: confirmation seeds 3-5, mean [min, max] of digit kNN accuracy, ARI
  (0-9), ARI (0/1, post hoc from ari_01_posthoc.csv), recall vs grass, and the wall-clock range per run (cluster job
  6087, one thread; graph construction included). Run names as in the report.
- docs/supervisor_report/figures/mnist09_seed3.png: confirmation seed 3 colored by digit (tab10 in digit order, as in
  scripts/mnist_grass_0to9_report.paper_figure), five runs, each captioned with its seed-3 digit kNN accuracy and ARI.
Needs the embeddings and data/processed/ (cluster).

    python scripts/supervisor_0to9.py
"""
import csv
import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402
from mpl_toolkits.axes_grid1.anchored_artists import AnchoredSizeBar  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from data import mnist_grass as mg  # noqa: E402
from scripts.mnist_grass_0to9_report import (DIGITS, FIG_SEED, NAME, OLD_RAW, OLD_RES, OUT,  # noqa: E402
                                             RUNS_DIR, read, round_length, run_json)

DOC = ROOT / "docs" / "supervisor_report"


def runs():
    """0-9 run -> (report name, 0/1 run of the same method for the post hoc ARI)."""
    sel = json.loads((OUT / "selection.json").read_text())
    m_c, m_rc = sel["c"]["best_m_B"], sel["r_c"]["best_m_B"]
    old_c = json.loads((OLD_RAW / "selection.json").read_text())["best_m_B"]
    old_rc = json.loads((OLD_RES / "selection.json").read_text())["best_m_B"]
    return {f"r_c_m{m_rc}": (rf"\BN{{}} ($m_B = {m_rc}$)", f"r_c_m{old_rc}"),
            "r_a": (r"\methodname{} (no background negatives)", "r_a"),
            f"c_m{m_c}": (rf"raw graph + background negatives ($m_B = {m_c}$)", f"c_m{old_c}"),
            "a": ("plain Neg-t-SNE (raw graph)", "a"), "T1": ("t-SNE", "T1"), "T2": (r"PCA-50$\to$t-SNE", "T2"),
            "T3": (r"cPCA$\to$t-SNE (label-free $\alpha$)", "T3")}


def fmt(v):
    v = np.asarray(v, dtype=float)
    return f"{v.mean():.3f} [{v.min():.3f}, {v.max():.3f}]"


def table():
    conf = read(OUT / "runs_confirmation.csv")
    with open(OUT / "ari_01_posthoc.csv") as f:
        ari01 = [r for r in csv.DictReader(f) if r["stage"] == "confirmation"]
    lines = [r"% generated by scripts/supervisor_0to9.py from results/mnist_grass_0to9/runs_confirmation.csv and",
             r"% results/mnist_grass_0to9/ari_01_posthoc.csv; do not edit by hand",
             r"\resizebox{\textwidth}{!}{\begin{tabular}{lccccc}", r"  \toprule",
             r"  run & digit acc. & ARI, 0--9 & ARI, 0/1 (post hoc) & recall vs grass & time per run (s) \\",
             r"  \midrule"]
    for run, (name, old) in runs().items():
        rr = [r for r in conf if r["run"] == run]
        t = [float(r["runtime_s"]) for r in rr]
        col = {m: fmt([float(r[m]) for r in rr]) for m in ("digit_acc", "ari", "recall_grass")}
        a01 = fmt([float(r["ari"]) for r in ari01 if r["run"] == old])
        lines.append(f"  {name} & {col['digit_acc']} & {col['ari']} & {a01} & {col['recall_grass']} "
                     f"& {min(t):.0f}--{max(t):.0f} \\\\")
    lines += [r"  \bottomrule", r"\end{tabular}}"]
    (DOC / "generated").mkdir(exist_ok=True)
    (DOC / "generated" / "tab_mnist09.tex").write_text("\n".join(lines) + "\n")


FIG_RUNS = {"r_c": "BC-NE+BN ($m_B$ = {m})", "r_a": "BC-NE (no background negatives)",
            "c": "raw graph + background negatives ($m_B$ = {m})", "T1": "t-SNE",
            "T3": r"cPCA$\to$t-SNE (label-free $\alpha$)"}


def figure():
    names = {r: n for r, (n, _) in runs().items()}
    chosen = []
    for key, caption in FIG_RUNS.items():
        run = next(r for r in names if r == key or r.startswith(f"{key}_m"))
        chosen.append((run, caption.format(m=run.split("_m")[-1])))
    y = mg.load(mg.processed_path(FIG_SEED, ROOT, name=NAME))["y"]
    colors = np.asarray(plt.get_cmap("tab10").colors)
    order = np.random.default_rng(0).permutation(len(y))  # fixed draw order: no digit painted last on purpose
    with plt.rc_context({"font.family": "serif", "mathtext.fontset": "cm"}):
        fig, axes = plt.subplots(2, 3, figsize=(10.5, 7.4))
        for ax, (run, caption) in zip(axes.flat, chosen):
            e = np.load(RUNS_DIR / f"confirmation_seed{FIG_SEED}_{run}.npy")[order]
            rec = run_json("confirmation", FIG_SEED, run)
            ax.scatter(*e.T, c=colors[y[order]], s=1, edgecolor="none", rasterized=True)
            ax.set_aspect("equal", adjustable="datalim")
            ax.axis("off")
            length = round_length(np.ptp(e[:, 0]))
            ax.add_artist(AnchoredSizeBar(ax.transData, length, f"{length:g}", "lower right", pad=0.1, sep=3,
                                          borderpad=0.2, frameon=False, size_vertical=0, fontproperties={"size": 9},
                                          label_top=False))
            ax.set_title(f"{caption}\ndigit kNN acc {rec['digit_acc']:.3f} · ARI {rec['ari']:.3f}", fontsize=10.5)
        legend_ax = axes.flat[len(chosen)]
        legend_ax.axis("off")
        handles = [plt.Line2D([], [], marker="o", ls="", ms=7, color=colors[d], label=str(d)) for d in DIGITS]
        legend_ax.legend(handles=handles, ncol=2, frameon=False, loc="center", fontsize=12, handletextpad=0.6,
                         columnspacing=2.5, labelspacing=0.9, title="digit", title_fontsize=12)
        fig.tight_layout(h_pad=2.5)
        fig.savefig(DOC / "figures" / f"mnist09_seed{FIG_SEED}.png", dpi=200, bbox_inches="tight")
        plt.close(fig)


def main():
    table()
    if "--table-only" not in sys.argv:
        figure()


if __name__ == "__main__":
    main()
