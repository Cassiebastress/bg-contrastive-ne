"""The supervisor report's cPCA-2D additions outside the 0-9 section (that one is in scripts/supervisor_0to9.py),
generated from stored results (no number typed by hand).

- docs/supervisor_report/generated/tab_additive.tex: the additive synthetic table, now generated, with a cPCA-2D column.
  Sources: results/phase4/headline.md (plain, best uniform, spectrum reference, background negatives) and
  results/phase5prep/cpca_summary.md ((e1) cPCA-2D and (e2) cPCA -> Neg-t-SNE), confirmation seeds, mean [min, max].
- docs/supervisor_report/generated/row_mnist_cpca2d.tex: the cPCA-2D row of the MNIST-on-grass 0/1 table
  (results/cpca2d_posthoc/runs.csv, confirmation seeds 3-5), without the closing row break, which main.tex supplies
  (a row break inside an input file breaks the table rule after it).
- docs/supervisor_report/figures/mnist_residual_seed3.png: scripts/bsgraph_report.figure's layout (confirmation seed 3,
  by digit and by grass brightness) with a fifth row, cPCA-2D. Needs the embeddings and data/processed/ (cluster).

    python scripts/supervisor_cpca2d.py               # tables and figure
    python scripts/supervisor_cpca2d.py --table-only
"""
import csv
import json
import re
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from data import mnist_grass as mg  # noqa: E402
from scripts.bsgraph_report import FIG_SEED, OUT as BSGRAPH, STORED, STORED_C, label  # noqa: E402

DOC = ROOT / "docs" / "supervisor_report"
POSTHOC = ROOT / "results" / "cpca2d_posthoc"
LEVELS = {"easy": "orthogonal", "medium": "overlapping", "hard": "nonlinear"}
CELL = re.compile(r"\d\.\d{3} \[\d\.\d{3}, \d\.\d{3}\]")


def md_rows(path):
    return [[c.strip() for c in ln.strip().strip("|").split("|")] for ln in path.read_text().splitlines()
            if ln.startswith("| ") and not ln.startswith("|---")]


def cell(text):
    """The 'mean [min, max]' part of a table cell (drops annotations such as '(m_B=20)')."""
    return CELL.search(text).group(0)


def additive_table():
    head = {r[0]: r for r in md_rows(ROOT / "results" / "phase4" / "headline.md") if r[0] in LEVELS}
    summary = (ROOT / "results" / "phase5prep" / "cpca_summary.md").read_text().split("## Appendix")[0]
    cpca = {}
    for level in LEVELS:
        section = summary.split(f"## {level} (")[1].split("\n## ")[0]
        main = section.split("\n\n| ")[1]  # the section's first table (metrics); the second holds the verdicts
        rows = {r[0]: r for r in (ln.strip().strip("|").split("|") for ln in ("| " + main).splitlines())}
        cpca[level] = {k.strip(): cell(rows[k][1]) for k in rows
                       if k.strip() in ("(e1) cPCA-2D", "(e2) cPCA -> Neg-t-SNE")}
    lines = [r"% generated by scripts/supervisor_cpca2d.py from results/phase4/headline.md and",
             r"% results/phase5prep/cpca_summary.md; do not edit by hand",
             r"\resizebox{\textwidth}{!}{\begin{tabular}{lcccccc}", r"  \toprule",
             r"  background & plain & uniform (best) & spectrum ref. & background neg. & cPCA-2D "
             r"& cPCA$\to$Neg-t-SNE \\", r"  \midrule"]
    for level, name in LEVELS.items():
        h = head[level]
        cells = [cell(h[2]), cell(h[3]), cell(h[4]), cell(h[5]), cpca[level]["(e1) cPCA-2D"],
                 cpca[level]["(e2) cPCA -> Neg-t-SNE"]]
        lines.append(f"  {name:<11} & " + " & ".join(cells) + r" \\")
    lines += [r"  \bottomrule", r"\end{tabular}}"]
    (DOC / "generated" / "tab_additive.tex").write_text("\n".join(lines) + "\n")


def posthoc(data, stage="confirmation"):
    with open(POSTHOC / "runs.csv") as f:
        return [r for r in csv.DictReader(f) if r["data"] == data and r["stage"] == stage]


def fmt(v):
    v = np.asarray(v, dtype=float)
    return f"{v.mean():.3f} [{v.min():.3f}, {v.max():.3f}]"


def mnist_row():
    rr = sorted(posthoc("0/1"), key=lambda r: int(r["seed"]))
    acc = [float(r["digit_acc"]) for r in rr]
    grass = np.mean([float(r["recall_grass"]) for r in rr])
    (DOC / "generated" / "row_mnist_cpca2d.tex").write_text(
        "% generated by scripts/supervisor_cpca2d.py from results/cpca2d_posthoc/runs.csv; do not edit by hand\n"
        f"cPCA-2D (post hoc) & {fmt(acc)} & " + " & ".join(f"{a:.3f}" for a in acc) + f" & {grass:.3f}\n")


def figure():
    """scripts/bsgraph_report.figure with a fifth row: the saved 2-D projection at T3's label-free alpha."""
    d = mg.load(mg.processed_path(FIG_SEED, ROOT))
    y, brightness = d["y"], d["grass_T"].mean(axis=1)
    rc = f"r_c_m{json.loads((BSGRAPH / 'selection.json').read_text())['best_m_B']}"
    panels = [(label(rc), BSGRAPH / "runs" / f"confirmation_seed{FIG_SEED}_{rc}"),
              (label("r_a"), BSGRAPH / "runs" / f"confirmation_seed{FIG_SEED}_r_a"),
              (label(STORED_C), STORED / "runs" / f"confirmation_seed{FIG_SEED}_{STORED_C}"),
              (label("T3"), STORED / "runs" / f"confirmation_seed{FIG_SEED}_T3"),
              ("cPCA-2D (post hoc)", None)]
    cp = next(r for r in posthoc("0/1") if int(r["seed"]) == FIG_SEED)
    fig, axes = plt.subplots(len(panels), 2, figsize=(6, 3 * len(panels)))
    for ax_row, (name, stem) in zip(axes, panels):
        if stem is None:
            with np.load(STORED / "runs" / f"confirmation_seed{FIG_SEED}_T3_cpca2d.npz") as f:
                e = f[f"{float(cp['alpha']):.6g}"]
            rec = {"digit_acc": float(cp["digit_acc"]), "recall_grass": float(cp["recall_grass"])}
        else:
            e = np.load(f"{stem}.npy")
            rec = json.loads(Path(f"{stem}.json").read_text())
        ax_row[0].scatter(*e.T, c=y, s=0.6, cmap="coolwarm", vmin=0, vmax=1, edgecolor="none", rasterized=True)
        sc = ax_row[1].scatter(*e.T, c=brightness, s=0.6, cmap="viridis", edgecolor="none", rasterized=True)
        ax_row[0].set_title(f"{name}\nby digit (blue 0, red 1): acc {rec['digit_acc']:.3f}", fontsize=7)
        ax_row[1].set_title(f"{name}\nby mean grass brightness: grass recall {rec['recall_grass']:.3f}", fontsize=7)
        fig.colorbar(sc, ax=ax_row[1], fraction=0.04)
        for ax in ax_row:
            ax.set_aspect("equal")
            ax.axis("off")
    fig.suptitle(f"Background-suppressed graph, MNIST-on-grass confirmation seed {FIG_SEED}", fontsize=9)
    fig.tight_layout(rect=(0, 0, 1, 0.99))
    fig.savefig(DOC / "figures" / f"mnist_residual_seed{FIG_SEED}.png", dpi=110, bbox_inches="tight")
    plt.close(fig)


def main():
    additive_table()
    mnist_row()
    if "--table-only" not in sys.argv:
        figure()


if __name__ == "__main__":
    main()
