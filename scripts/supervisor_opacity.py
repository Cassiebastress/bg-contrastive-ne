"""The supervisor report's digit-opacity table and figure, generated from results/mnist_grass_opacity/ (no number typed
by hand; nothing is recomputed except the plot).

- docs/supervisor_report/generated/tab_opacity.tex: all six seeds, mean digit kNN accuracy and mean ARI (k-means,
  k = 2) of BC-NE, t-SNE and cPCA -> t-SNE at w = 0.25 down to 0.06.
- docs/supervisor_report/figures/opacity_seed3.png: t-SNE and BC-NE side by side at the same w (seed 3), each without
  labels and colored by digit; the layout of scripts/opacity_report.side_by_side_figure, cropped at w = 0.06.
Needs the embeddings and data/processed/ (cluster) for the figure.

    python scripts/supervisor_opacity.py               # table and figure
    python scripts/supervisor_opacity.py --table-only
"""
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.opacity_report import DIGIT_COLORS, FIG_SEED, GRAY, RULE, read, vals  # noqa: E402
from scripts.opacity_run import RUNS_DIR, W_STORED, load, name  # noqa: E402

DOC = ROOT / "docs" / "supervisor_report"
WS = (0.25, 0.20, 0.15, 0.10, 0.08, 0.06)
RUNS = {"r_a": r"\methodname{}", "T1": "t-SNE", "T3": r"cPCA$\to$t-SNE"}


def table():
    rows = read("selection") + read("confirmation")
    lines = [r"% generated by scripts/supervisor_opacity.py from results/mnist_grass_opacity/runs_{selection,"
             r"confirmation}.csv;", r"% do not edit by hand",
             r"\begin{tabular}{lcccccc}", r"  \toprule",
             r"  & \multicolumn{3}{c}{digit kNN accuracy} & \multicolumn{3}{c}{ARI} \\",
             r"  \cmidrule(lr){2-4} \cmidrule(lr){5-7}",
             "  $w$ & " + " & ".join(list(RUNS.values()) * 2) + r" \\", r"  \midrule"]
    for w in WS:
        cells = [f"{np.mean(vals(rows, run, w, m)):.3f}" for m in ("digit_acc", "ari") for run in RUNS]
        lines.append(f"  {w:.2f} & " + " & ".join(cells) + r" \\")
    lines += [r"  \bottomrule", r"\end{tabular}"]
    (DOC / "generated").mkdir(exist_ok=True)
    (DOC / "generated" / "tab_opacity.tex").write_text("\n".join(lines) + "\n")


def figure():
    _, _, t = load(FIG_SEED, W_STORED)
    order = np.random.default_rng(0).permutation(len(t["y"]))
    cols = [("T1", None), ("T1", t["y"]), ("r_a", None), ("r_a", t["y"])]
    with plt.rc_context({"font.family": "serif", "mathtext.fontset": "cm"}):
        fig, axes = plt.subplots(len(WS), len(cols), figsize=(3.6, 0.88 * len(WS)))
        for i, w in enumerate(WS):
            emb = {run: np.load(RUNS_DIR / f"{name('confirmation', FIG_SEED, w, run)}.npy") for run in ("T1", "r_a")}
            for j, (run, y) in enumerate(cols):
                ax, e = axes[i, j], emb[run][order]
                ax.scatter(*e.T, c=GRAY if y is None else DIGIT_COLORS[y[order]], s=0.2, edgecolor="none",
                           rasterized=True)  # panels a third the size of side_by_side_figure's: smaller points
                ax.set_aspect("equal", adjustable="datalim")
                ax.axis("off")
            axes[i, 0].text(-0.1, 0.5, f"$w$ = {w:.2f}", transform=axes[i, 0].transAxes, ha="right", va="center",
                            fontsize=9)
        for j, (run, y) in enumerate(cols):
            axes[0, j].set_title("no labels" if y is None else "by digit", fontsize=7.5)
        fig.tight_layout(rect=(0.07, 0, 1, 0.97), h_pad=0.3, w_pad=0.3)
        for j, label in ((0, "t-SNE"), (2, "BC-NE")):
            mid = (axes[0, j].get_position().x0 + axes[0, j + 1].get_position().x1) / 2
            fig.text(mid, 0.995, label, ha="center", va="top", fontsize=9)
        x = (axes[0, 1].get_position().x1 + axes[0, 2].get_position().x0) / 2
        fig.add_artist(plt.Line2D([x, x], [0.01, 0.99], transform=fig.transFigure, color=RULE, lw=1))
        fig.savefig(DOC / "figures" / f"opacity_seed{FIG_SEED}.png", dpi=300, bbox_inches="tight")
        plt.close(fig)


def main():
    table()
    if "--table-only" not in sys.argv:
        figure()


if __name__ == "__main__":
    main()
