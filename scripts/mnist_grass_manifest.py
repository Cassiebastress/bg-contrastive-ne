"""Write data/MANIFEST.md for the MNIST-on-grass inputs (run on the cluster, where data/raw/ lives).

Checks (stop and report on failure): data/raw/grass/ holds exactly 1272 images, every one readable by Pillow;
data/raw/mnist.npz matches the SHA-256 that Keras pins for it. Lists the file count, the extensions found, and a
SHA-256 per file; adds data/processed/*.npz if present (after scripts/mnist_grass_build.py).

    python scripts/mnist_grass_manifest.py
"""
import hashlib
import sys
from collections import Counter
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RAW, PROCESSED = ROOT / "data" / "raw", ROOT / "data" / "processed"
N_GRASS = 1272  # .JPEG files in ImageNet-20261030T152523Z-1-001.zip (the Drive folder of the cPCA authors)
MNIST_SHA256 = "731c5ac602752760c8e48fbffcf8c3b850d9dc2a2aedcf2cc48468fc17b673d1"  # keras.datasets.mnist file_hash


def stop(msg):
    print(f"STOP (MNIST-on-grass data intake): {msg}", flush=True)
    sys.exit(2)


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def main():
    files = sorted(p for p in (RAW / "grass").iterdir() if p.is_file())
    if len(files) != N_GRASS:
        stop(f"{len(files)} files in data/raw/grass/, expected {N_GRASS}")
    for p in files:
        try:
            with Image.open(p) as im:
                im.verify()
        except Exception as e:  # noqa: BLE001 - any unreadable file stops the intake
            stop(f"unreadable image {p.name}: {e}")
    mnist = sha256(RAW / "mnist.npz")
    if mnist != MNIST_SHA256:
        stop(f"mnist.npz SHA-256 {mnist} differs from the Keras-pinned {MNIST_SHA256}")
    ext = Counter(p.suffix for p in files)
    lines = ["# MNIST-on-grass data manifest", "",
             "Generated by `scripts/mnist_grass_manifest.py` on the cluster. The files themselves are not committed "
             "(size and ImageNet terms; `data/raw/` and `data/processed/` are gitignored).", "",
             "## Sources", "",
             "- Grass: `ImageNet-20261030T152523Z-1-001.zip`, the cPCA authors' Google Drive folder of ImageNet "
             "synset n12102133 images, unzipped into `data/raw/grass/`.",
             "- MNIST: `https://storage.googleapis.com/tensorflow/tf-keras-datasets/mnist.npz`, into `data/raw/`; "
             "its SHA-256 matches the hash Keras pins.", "",
             "## Summary", "", f"- grass images: {len(files)}",
             f"- extensions: {', '.join(f'{e} ({n})' for e, n in sorted(ext.items()))}",
             f"- `mnist.npz` SHA-256: `{mnist}`", ""]
    processed = sorted(PROCESSED.glob("*.npz")) if PROCESSED.exists() else []
    if processed:
        lines += ["## Processed datasets (`data/processed/`)", "", "| file | SHA-256 |", "|---|---|"]
        lines += [f"| `{p.name}` | `{sha256(p)}` |" for p in processed] + [""]
    lines += ["## Grass files (`data/raw/grass/`, sorted)", "", "| file | SHA-256 |", "|---|---|"]
    lines += [f"| `{p.name}` | `{sha256(p)}` |" for p in files]
    (ROOT / "data" / "MANIFEST.md").write_text("\n".join(lines) + "\n")
    print(f"ok: {len(files)} grass images {dict(ext)}, mnist.npz verified, {len(processed)} processed files")


if __name__ == "__main__":
    main()
